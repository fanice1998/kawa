package llm

import (
	"encoding/json"
	"regexp"
	"strings"
	"unicode/utf8"

	"github.com/rs/zerolog/log"
)

var thinkBlockRe = regexp.MustCompile(`(?is)<think>.*?</think>`)

// PreFlightReport summarizes the format & content checks performed before sending a payload to an LLM.
type PreFlightReport struct {
	OriginalMessages int      `json:"original_messages"`
	CleanedMessages  int      `json:"cleaned_messages"`
	TotalRunes       int      `json:"total_runes"`
	FixesApplied     []string `json:"fixes_applied,omitempty"`
}

// SanitizeAndValidateRequest performs a comprehensive pre-flight check and normalization
// on ChatRequest before it is transmitted to any LLM provider (especially strict templates like Qwen3 / Ollama):
// 1. Cleans invalid UTF-8 sequences and control characters.
// 2. Strips historical `<think>...</think>` reasoning blocks from prior assistant turns.
// 3. Drops empty messages that lack both Content and ToolCalls.
// 4. Merges consecutive User messages to preserve strict role alternation (`system -> user -> assistant`).
// 5. Validates all tool parameter JSON schemas and tool call arguments.
func SanitizeAndValidateRequest(req ChatRequest) (ChatRequest, PreFlightReport) {
	report := PreFlightReport{
		OriginalMessages: len(req.Messages),
	}

	var cleanedMsgs []Message
	for _, m := range req.Messages {
		content := sanitizeText(m.Content, &report)

		// Strip historical <think>...</think> blocks from previous assistant messages
		if m.Role == RoleAssistant && strings.Contains(content, "<think>") {
			stripped := StripThinkingTags(content)
			if stripped != content {
				content = stripped
				report.FixesApplied = appendUnique(report.FixesApplied, "stripped_historical_think_tags")
			}
		}

		// Validate ToolCalls arguments are valid JSON objects
		var validToolCalls []ToolCall
		for _, tc := range m.ToolCalls {
			args := strings.TrimSpace(tc.Arguments)
			if args == "" || !json.Valid([]byte(args)) {
				args = "{}"
				report.FixesApplied = appendUnique(report.FixesApplied, "repaired_invalid_tool_call_json")
			}
			validToolCalls = append(validToolCalls, ToolCall{
				ID:        tc.ID,
				Name:      strings.TrimSpace(tc.Name),
				Arguments: args,
			})
		}

		// Drop completely empty assistant/user messages that have no tool calls
		if strings.TrimSpace(content) == "" && len(validToolCalls) == 0 {
			report.FixesApplied = appendUnique(report.FixesApplied, "dropped_empty_message")
			continue
		}

		msg := Message{
			Role:       m.Role,
			Content:    content,
			ToolCallID: m.ToolCallID,
			ToolName:   m.ToolName,
			ToolCalls:  validToolCalls,
		}

		// Merge consecutive User messages so strict chat templates don't fail on user->user
		if len(cleanedMsgs) > 0 && msg.Role == RoleUser && cleanedMsgs[len(cleanedMsgs)-1].Role == RoleUser {
			cleanedMsgs[len(cleanedMsgs)-1].Content += "\n\n" + msg.Content
			report.FixesApplied = appendUnique(report.FixesApplied, "merged_consecutive_user_messages")
			continue
		}

		cleanedMsgs = append(cleanedMsgs, msg)
	}

	// Validate ToolDefinitions JSON schema
	var validTools []ToolDefinition
	for _, t := range req.Tools {
		params := t.Parameters
		if len(params) == 0 || !json.Valid(params) {
			params = json.RawMessage(`{"type":"object","properties":{}}`)
			report.FixesApplied = appendUnique(report.FixesApplied, "repaired_tool_schema_json")
		}
		validTools = append(validTools, ToolDefinition{
			Name:        strings.TrimSpace(t.Name),
			Description: sanitizeText(t.Description, &report),
			Parameters:  params,
		})
	}

	for _, m := range cleanedMsgs {
		report.TotalRunes += utf8.RuneCountInString(m.Content)
	}
	report.CleanedMessages = len(cleanedMsgs)

	if len(report.FixesApplied) > 0 {
		log.Info().
			Int("orig_msgs", report.OriginalMessages).
			Int("clean_msgs", report.CleanedMessages).
			Int("total_runes", report.TotalRunes).
			Strs("fixes", report.FixesApplied).
			Msg("Pre-flight payload validator sanitized LLM request")
	}

	return ChatRequest{
		Messages: cleanedMsgs,
		Tools:    validTools,
	}, report
}

// StripThinkingTags removes `<think>...</think>` reasoning blocks generated by Qwen3 / DeepSeek models
// so only the final actionable content or JSON is returned to the caller.
func StripThinkingTags(s string) string {
	cleaned := thinkBlockRe.ReplaceAllString(s, "")
	// Also handle unclosed <think> if the model was cut off mid-thought
	if idx := strings.Index(cleaned, "<think>"); idx != -1 {
		cleaned = cleaned[:idx]
	}
	return strings.TrimSpace(cleaned)
}

func sanitizeText(s string, report *PreFlightReport) string {
	if !utf8.ValidString(s) {
		s = strings.ToValidUTF8(s, "")
		if report != nil {
			report.FixesApplied = appendUnique(report.FixesApplied, "repaired_invalid_utf8")
		}
	}
	// Remove NUL and non-printable control chars (except \n, \r, \t)
	var sb strings.Builder
	sb.Grow(len(s))
	removedCtrl := false
	for _, r := range s {
		if r == 0 || (r < 32 && r != '\n' && r != '\r' && r != '\t') {
			removedCtrl = true
			continue
		}
		sb.WriteRune(r)
	}
	if removedCtrl && report != nil {
		report.FixesApplied = appendUnique(report.FixesApplied, "removed_control_chars")
	}
	return sb.String()
}

func appendUnique(slice []string, item string) []string {
	for _, s := range slice {
		if s == item {
			return slice
		}
	}
	return append(slice, item)
}
